"""Regression tests for page_layout_detector's footnote-boundary stage.

Locks the current tuned behavior of:

    detect_horizontal_gaps()
    detect_separator_lines()
    find_footnote_boundary()

Real-manuscript fixtures (pages 4, 8, 27, 28, 95, 111) are golden snapshots
generated by tests/fixtures/layout/generate_fixtures.py from the exact
production chain at 200 DPI. See tests/fixtures/layout/README.md.

The synthetic fixtures (S7-S13) cover constant-boundary and adversarial
geometry that no real page exercises deterministically. No production code
is imported for writing - only for reading detector output.
"""

import json
import os
import unittest

import cv2
import numpy as np

from src.pipeline.preprocessing import page_layout_detector as layout

FIXTURE_DIR = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "fixtures", "layout"
)
MANIFEST_PATH = os.path.join(FIXTURE_DIR, "manifest.json")
HAS_FIXTURES = os.path.isfile(MANIFEST_PATH)

REAL_PAGES = [4, 8, 27, 28, 95, 111]

BOUNDARY_FIELDS = [
    "score",
    "detected",
    "footnote_y",
    "candidate_y",
    "has_gap",
    "gap_y",
    "has_separator",
    "separator_y",
    "has_smaller_text",
    "match_tolerance",
]

PAGE_W, PAGE_H = 400, 1000


def _native(value):
    """Recursively convert numpy scalars/arrays to plain Python types."""
    if isinstance(value, (np.bool_, bool)):
        return bool(value)
    if isinstance(value, np.integer):
        return int(value)
    if isinstance(value, np.floating):
        return float(value)
    if isinstance(value, np.ndarray):
        return [_native(v) for v in value]
    if isinstance(value, dict):
        return {k: _native(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_native(v) for v in value]
    return value


def _read_json(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def _load_real_page(page):
    binary = cv2.imread(
        os.path.join(FIXTURE_DIR, "page_%03d_binary.png" % page),
        cv2.IMREAD_GRAYSCALE,
    )
    if binary is None:
        raise AssertionError("missing binary fixture for page %d" % page)
    boxes_obj = _read_json(os.path.join(FIXTURE_DIR, "page_%03d_boxes.json" % page))
    cb_obj = _read_json(os.path.join(FIXTURE_DIR, "page_%03d_cb.json" % page))
    expected = _read_json(
        os.path.join(FIXTURE_DIR, "page_%03d_expected.json" % page)
    )
    boxes = [tuple(int(v) for v in box) for box in boxes_obj["boxes"]]
    content_bbox = tuple(int(v) for v in cb_obj["content_bbox"])
    return binary, boxes, content_bbox, expected


# ---------------------------------------------------------------------------
# Synthetic fixture builders
#
# Page convention matches layout.binarize_to_255() output: background = 0, "ink" = 255.
# "Text" is drawn as narrow dash rows (30 px wide) so it can never satisfy the
# separator width ratios; rules are drawn explicitly where a separator is
# wanted, which keeps gap-only and separator-only geometry independent.
# ---------------------------------------------------------------------------

def _blank(width=PAGE_W, height=PAGE_H):
    return np.zeros((height, width), np.uint8)


def _dash_rows(img, y0, y1, x0=40, x1=70):
    img[y0:y1, x0:x1] = 255


def _rule(img, y, x0, x1):
    img[y, x0:x1] = 255


def _synthetic_boxes(candidate_y, size=20):
    """Same-size text components above and below candidate_y."""
    above = [
        (40, candidate_y - 125, 100, size),
        (40, candidate_y - 85, 100, size),
        (40, candidate_y - 45, 100, size),
    ]
    below = [
        (40, candidate_y + 15, 100, size),
        (40, candidate_y + 55, 100, size),
        (40, candidate_y + 95, 100, size),
    ]
    return above + below


class TestDetectHorizontalGaps(unittest.TestCase):

    @unittest.skipUnless(HAS_FIXTURES, "layout fixtures not generated")
    def test_real_pages_exact_gap_lists(self):
        for page in REAL_PAGES:
            binary, _boxes, content_bbox, expected = _load_real_page(page)
            actual = _native(layout.detect_horizontal_gaps(binary, content_bbox))
            self.assertEqual(actual, expected["gaps"], "page %d gaps" % page)

    def test_min_gap_height_boundary_s11(self):
        # MIN_GAP_HEIGHT_PX == 12: a 12-row empty run is a gap, 11 rows is not.
        content_bbox = (0, 0, PAGE_W, PAGE_H)

        img12 = _blank()
        _dash_rows(img12, 550, 559)
        _dash_rows(img12, 571, 600)
        self.assertEqual(
            _native(layout.detect_horizontal_gaps(img12, content_bbox)),
            [{"start_y": 559, "end_y": 571, "height": 12}],
        )

        img11 = _blank()
        _dash_rows(img11, 550, 559)
        _dash_rows(img11, 570, 600)
        self.assertEqual(
            _native(layout.detect_horizontal_gaps(img11, content_bbox)), []
        )

    def test_trailing_gap_not_reported_s12(self):
        # A gap that opens and runs to the bottom of the region is never
        # closed, so it is not reported (documented trailing-gap hole).
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        img = _blank()
        _dash_rows(img, 550, 559)
        self.assertEqual(
            _native(layout.detect_horizontal_gaps(img, content_bbox)), []
        )

    def test_empty_region_returns_empty_s13a(self):
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        self.assertEqual(layout.detect_horizontal_gaps(_blank(), content_bbox), [])


class TestDetectSeparatorLines(unittest.TestCase):

    @unittest.skipUnless(HAS_FIXTURES, "layout fixtures not generated")
    def test_real_pages_exact_separator_lists(self):
        for page in REAL_PAGES:
            binary, _boxes, content_bbox, expected = _load_real_page(page)
            actual = _native(layout.detect_separator_lines(binary, content_bbox))
            self.assertEqual(
                actual, expected["separators"], "page %d separators" % page
            )

    def test_method_a_morphology_rule(self):
        # A 400 px rule (>= SEPARATOR_LINE_MIN_WIDTH_RATIO 0.20 of 400) is
        # caught by the morphology path.
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        img = _blank()
        _rule(img, 700, 0, PAGE_W)
        self.assertEqual(
            _native(layout.detect_separator_lines(img, content_bbox)), [700]
        )

    def test_method_b_only_short_rule_s9a(self):
        # 60 px wide: >= SEPARATOR_CONTOUR_MIN_WIDTH_RATIO 0.12 (48) but
        # < SEPARATOR_LINE_MIN_WIDTH_RATIO 0.20 (80), so the morphology
        # kernel removes it and only the contour path catches it.
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        img = _blank()
        _rule(img, 700, 150, 210)
        self.assertEqual(
            _native(layout.detect_separator_lines(img, content_bbox)), [700]
        )

    def test_bottom_exclusion_band_rule_s10(self):
        # SEPARATOR_BOTTOM_EXCLUSION_RATIO 0.06 -> bottom_cutoff 940; a rule
        # at 960 is treated as page frame and ignored.
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        img = _blank()
        _rule(img, 960, 0, PAGE_W)
        self.assertEqual(layout.detect_separator_lines(img, content_bbox), [])

    def test_empty_region_returns_empty_s13b(self):
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        self.assertEqual(layout.detect_separator_lines(_blank(), content_bbox), [])


class TestFindFootnoteBoundaryRealPages(unittest.TestCase):

    @unittest.skipUnless(HAS_FIXTURES, "layout fixtures not generated")
    def test_real_pages_exact_boundary_fields(self):
        for page in REAL_PAGES:
            binary, boxes, content_bbox, expected = _load_real_page(page)
            actual = _native(
                layout.find_footnote_boundary(binary, content_bbox, boxes)
            )
            for field in BOUNDARY_FIELDS:
                self.assertEqual(
                    actual[field],
                    expected["boundaries"][field],
                    "page %d field %s" % (page, field),
                )

    @unittest.skipUnless(HAS_FIXTURES, "layout fixtures not generated")
    def test_real_pages_derived_invariants(self):
        for page in REAL_PAGES:
            binary, boxes, content_bbox, _expected = _load_real_page(page)
            actual = _native(
                layout.find_footnote_boundary(binary, content_bbox, boxes)
            )
            content_height = max(1, content_bbox[3] - content_bbox[1])

            self.assertEqual(
                actual["detected"],
                actual["score"] >= layout.FOOTNOTE_SCORE_THRESHOLD,
                "page %d detected/score invariant" % page,
            )
            if actual["detected"]:
                self.assertEqual(actual["footnote_y"], actual["candidate_y"])
            else:
                self.assertEqual(actual["footnote_y"], content_bbox[3])
            self.assertEqual(
                actual["match_tolerance"],
                max(
                    8,
                    int(content_height * layout.BOUNDARY_MATCH_TOLERANCE_RATIO),
                ),
            )

    @unittest.skipUnless(HAS_FIXTURES, "layout fixtures not generated")
    def test_page_27_separator_present_but_isolated(self):
        # Page 27 is a NEAR-MISS, NOT an absence-of-detection case: a
        # separator rule IS detected at y=3421 (has_separator=True), but no
        # gap lies within match_tolerance of it, so score stays 1 and the
        # page is NOT cut. This locks the real-manuscript guard for the
        # review's risk #1/#2. See page_027_expected.json's "note".
        binary, boxes, content_bbox, _expected = _load_real_page(27)
        actual = _native(layout.find_footnote_boundary(binary, content_bbox, boxes))

        self.assertTrue(actual["has_separator"])
        self.assertEqual(actual["separator_y"], 3421)
        self.assertFalse(actual["has_gap"])
        self.assertEqual(actual["score"], 1)
        self.assertFalse(actual["detected"])
        self.assertEqual(actual["footnote_y"], content_bbox[3])


class TestFindFootnoteBoundarySynthetic(unittest.TestCase):

    def test_empty_region_s13(self):
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        actual = _native(layout.find_footnote_boundary(_blank(), content_bbox, []))
        self.assertEqual(actual["score"], 0)
        self.assertFalse(actual["detected"])
        self.assertIsNone(actual["candidate_y"])
        self.assertEqual(actual["footnote_y"], PAGE_H)
        self.assertFalse(actual["has_gap"])
        self.assertFalse(actual["has_separator"])
        self.assertFalse(actual["has_smaller_text"])
        self.assertEqual(
            actual["match_tolerance"],
            max(8, int(PAGE_H * layout.BOUNDARY_MATCH_TOLERANCE_RATIO)),
        )

    def test_gap_only_never_cuts_s11(self):
        # A lone 12 px gap scores 1: detected False, footnote_y == y2.
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        img = _blank()
        _dash_rows(img, 550, 559)
        _dash_rows(img, 571, 900)
        boxes = _synthetic_boxes(700)
        actual = _native(layout.find_footnote_boundary(img, content_bbox, boxes))

        self.assertTrue(actual["has_gap"])
        self.assertFalse(actual["has_separator"])
        self.assertEqual(actual["score"], 1)
        self.assertFalse(actual["detected"])
        self.assertEqual(actual["footnote_y"], PAGE_H)


class TestFootnoteFalsePositiveRisk(unittest.TestCase):
    """Documents the review's risk #1/#2 with adversarial synthetic geometry.

    These tests pin CURRENT behavior. They are not an endorsement that the
    behavior is correct; they exist so a deliberate heuristic change is
    caught and reviewed rather than slipping through silently.
    """

    def test_s7_aligned_gap_and_rule_false_cut(self):
        # S7 (ADVERSARIAL): a plain inter-stanza gap (25 px, >= MIN_GAP_HEIGHT_PX)
        # in the bottom 45% coincides with a thin rule inside match_tolerance,
        # and the text above/below is the SAME size, so the font-size signal
        # is absent. Current tuned behavior: score = 2 (gap + separator) ->
        # detected True.
        #
        # This is the false-cut shape flagged in the review (risk #1/#2). If
        # the heuristic is deliberately changed (e.g. requiring the font-size
        # signal), THIS TEST MUST FAIL AND BE UPDATED.
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        img = _blank()
        _dash_rows(img, 550, 700)
        _rule(img, 725, 40, 360)  # empty rows 700..724 form the gap
        _dash_rows(img, 730, 900)
        boxes = _synthetic_boxes(725)
        actual = _native(layout.find_footnote_boundary(img, content_bbox, boxes))

        self.assertTrue(actual["has_gap"])
        self.assertTrue(actual["has_separator"])
        self.assertFalse(actual["has_smaller_text"])
        self.assertEqual(actual["score"], 2)
        self.assertTrue(actual["detected"])
        self.assertEqual(actual["candidate_y"], 725)
        self.assertEqual(actual["footnote_y"], 725)

    def test_s8_misaligned_rule_does_not_cut(self):
        # S8 (CONTROL): identical geometry, but the rule sits farther than
        # match_tolerance from the gap, so the signals cannot combine and the
        # page is not cut (score = 1).
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        img = _blank()
        _dash_rows(img, 550, 700)
        _rule(img, 780, 40, 360)
        _dash_rows(img, 790, 900)
        boxes = _synthetic_boxes(700)
        actual = _native(layout.find_footnote_boundary(img, content_bbox, boxes))

        self.assertEqual(actual["score"], 1)
        self.assertFalse(actual["detected"])
        self.assertEqual(actual["footnote_y"], PAGE_H)

    def test_s9_method_b_only_rule_also_feeds_false_cut(self):
        # S9 (risk #2): a shorter kashida/underline-shaped rule (caught only
        # by the contour method), aligned with a gap, still scores 2.
        content_bbox = (0, 0, PAGE_W, PAGE_H)
        img = _blank()
        _dash_rows(img, 550, 700)
        _rule(img, 725, 150, 210)  # 60 px wide: Method B only
        _dash_rows(img, 730, 900)
        boxes = _synthetic_boxes(725)

        self.assertEqual(
            _native(layout.detect_separator_lines(img, content_bbox)), [725]
        )
        actual = _native(layout.find_footnote_boundary(img, content_bbox, boxes))
        self.assertEqual(actual["score"], 2)
        self.assertTrue(actual["detected"])
        self.assertEqual(actual["footnote_y"], 725)


